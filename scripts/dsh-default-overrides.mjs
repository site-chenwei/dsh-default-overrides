import { existsSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { isAbsolute, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BASH_RUNTIME_SERVICE, bashRuntimeDescription, bashPathGuidance } from './bash-runtime.mjs';

// Note: 包根导出与 bundle 共用此入口，安装接线由补丁提供 — 见 .agents/notes/implemented/architecture/2026-09-24-distributable-dsh-bundle.md。
export const name = 'dsh-default-overrides';
export const inject = ['loader', 'agentPresets'];

const SHIPPED_SHELL_ROWS = [
  { id: 'tool-bash', name: '@deepseek-ai/dsh-tool-bash' },
  { id: 'tool-pwsh', name: '@deepseek-ai/dsh-tool-pwsh' },
];
const SHELL_MODES = ['persistent-bash', 'persistent-pwsh', 'bash', 'pwsh'];
const SHELL_GROUP_ID = 'local-standard-persistent-shell';
const ENVIRONMENT_SECTION = 'local:dsh-default-overrides:environment';
const PERSONA_ROW = { id: 'persona', name: '@deepseek-ai/dsh-persona' };
const PERSONA_KEYS = ['prefix', 'suffix', 'complete', 'includeRuntimeContext'];
// persona 名单对所有预设一视同仁；省略时只覆盖 standard。
const DEFAULT_PERSONA_PRESETS = ['standard'];
const SHIM_FILENAME = 'dsh-default-overrides-bashrc.sh';

/** 单引号包裹 bash 参数，路径含单引号时按 POSIX 规则转义。 */
function quoteBash(value) {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/**
 * 生成交互式 bash 的启动垫片：持久化工具把命令包成 `eval -- $'...'`，
 * 垫片在 eval 前用同一个归一化模块改写 Windows 路径。
 */
function writeBashShim() {
  const node = process.execPath.replaceAll('\\', '/');
  const normalizer = fileURLToPath(new URL('./command-paths.mjs', import.meta.url)).replaceAll('\\', '/');
  const shim = [
    '# Generated by dsh-default-overrides on every DSH start; do not edit.',
    '__dsh_default_overrides_eval() {',
    '  if [[ $# -eq 2 && $1 == -- && $2 =~ [A-Za-z]:\\\\ ]]; then',
    '    local __dsh_normalized',
    `    __dsh_normalized=$(printf '%s' "$2" | ${quoteBash(node)} ${quoteBash(normalizer)} 2>/dev/null)`,
    '    if [[ -n $__dsh_normalized ]]; then',
    '      builtin eval -- "$__dsh_normalized"',
    '      return',
    '    fi',
    '  fi',
    '  builtin eval "$@"',
    '}',
    'eval() { __dsh_default_overrides_eval "$@"; }',
    '',
  ].join('\n');
  const path = join(tmpdir(), SHIM_FILENAME);
  writeFileSync(path, shim, { mode: 0o600 });
  return path.replaceAll('\\', '/');
}

/** 在 command 参数说明上补一句路径写法，紧挨模型实际填写的位置。 */
function commandParameterHint(parameters, dialect, facts) {
  const command = parameters?.properties?.command;
  if (typeof command?.description !== 'string') return parameters;
  const hint = dialect === 'bash'
    ? ` ${bashPathGuidance(facts)}`
    : ' Quote paths containing spaces.';
  return { ...parameters, properties: { ...parameters.properties, command: { ...command, description: `${command.description}${hint}` } } };
}

/** 校验 persona 覆盖项；键名或类型写错时直接报错，避免静默不生效。 */
function verifyPersonaOption(persona) {
  if (persona === null || typeof persona !== 'object' || Array.isArray(persona)) {
    throw new Error(`dsh-default-overrides: persona must be an object using ${PERSONA_KEYS.join(', ')}`);
  }
  const keys = Object.keys(persona);
  const unknown = keys.filter(key => !PERSONA_KEYS.includes(key));
  if (unknown.length > 0) {
    throw new Error(`dsh-default-overrides: persona has unsupported keys ${unknown.map(key => JSON.stringify(key)).join(', ')}; allowed: ${PERSONA_KEYS.join(', ')}`);
  }
  if (keys.length === 0) {
    throw new Error(`dsh-default-overrides: persona needs at least one of ${PERSONA_KEYS.join(', ')}`);
  }
  for (const key of ['prefix', 'suffix']) {
    if (persona[key] !== undefined && typeof persona[key] !== 'string') {
      throw new Error(`dsh-default-overrides: persona.${key} must be a string`);
    }
  }
  for (const key of ['complete', 'includeRuntimeContext']) {
    if (persona[key] !== undefined && typeof persona[key] !== 'boolean') {
      throw new Error(`dsh-default-overrides: persona.${key} must be a boolean`);
    }
  }
}

/** 操作规则补充官方说明；不声称 PATH 遮蔽或系统级 Shell 隔离。 */
function shellGuidance(dialect, facts) {
  return dialect === 'bash'
    ? [
      facts ? bashRuntimeDescription(facts) : 'Use Bash syntax with the configured Bash executable.',
      'This is the selected shell channel. Do not invoke cmd, powershell or pwsh (including .exe or absolute paths) to wrap a command or retry a failure. Run native programs directly; if a different shell is required, explain the need to the user.',
      bashPathGuidance(facts),
    ].join(' ')
    : [
      'Use PowerShell syntax with the configured PowerShell executable.',
      'This is the selected shell channel. Do not invoke cmd, bash or sh (including .exe or absolute paths) to wrap a command or retry a failure. Run native programs directly; if a different shell is required, explain the need to the user.',
      'Quote paths containing spaces; PowerShell uses a backtick as the escape character. Read environment variables with $env:NAME.',
    ].join(' ');
}

/**
 * 环境事实段：平台与工作区在任何配置下都成立；Shell 通道细节只在插件确实接管了该通道时声明。
 * 未接管时宿主自己决定工具（fallback 在 Windows 上是 pwsh），所以不冒充方言、不声称本插件的 timeoutMs 生效。
 */
function environmentContext({ managed, mode, persistent, timeoutMs, hasWorkspace }) {
  const lines = [managed
    ? `Host platform: ${process.platform}. Shell mode: ${mode}. Executable: {{dsh_overrides_shell_path}}.`
    : `Host platform: ${process.platform}. Shell channel: supplied by the active preset or the host default; this plugin configured no shell.`];
  if (managed) {
    lines.push(persistent
      ? `Arguments: command only. Working directory, variables and functions persist while the shell stays alive. The command deadline is ${timeoutMs} ms; exit, timeout, cancellation or restart resets shell state.`
      : 'Required arguments: command and description. Each call starts a fresh shell; use workdir for the working directory. Follow the tool schema for timeoutMs and background execution; a foreground wait timeout may promote the command to a background job.');
  }
  if (hasWorkspace) {
    lines.push(`Session workspace: {{dsh_overrides_workspace}}. File tools resolve relative paths from this workspace.${managed && persistent ? ' A persistent shell may have changed its own directory.' : ''}`);
  }
  return lines.join('\n');
}

/** 拍平预设行，group 行自身也在结果中。 */
function flattenRows(rows) {
  const flat = [];
  function visit(entries) {
    for (const row of entries) {
      flat.push(row);
      if (row.group === true) visit(row.config);
    }
  }
  visit(rows);
  return flat;
}

/** 校验 standard 的 Shell 替换目标；上游改结构时明确报错。 */
function verifyShellRows(flat) {
  for (const row of SHIPPED_SHELL_ROWS) {
    const matches = flat.filter(candidate => candidate.id === row.id);
    if (matches.length !== 1 || matches[0].name !== row.name) {
      throw new Error(`dsh-default-overrides: shipped preset changed at ${row.id}; review shell compatibility`);
    }
  }
  if (flat.some(row => row.id === SHELL_GROUP_ID)) {
    throw new Error('dsh-default-overrides: the shipped preset already contains the local shell group');
  }
}

// Note: ready 保证钩子先于预设注册，禁止修改宿主 PATH — 见 .agents/notes/implemented/bug-fix/2026-09-24-shell-channel-runtime-contracts.md。
export async function apply(ctx, options = {}) {
  const mode = options.shellMode;
  const shellEnabled = mode !== undefined;
  if (shellEnabled && !SHELL_MODES.includes(mode)) {
    throw new Error(`dsh-default-overrides: shellMode must be one of ${SHELL_MODES.join(', ')}, got ${JSON.stringify(mode)}`);
  }
  if (options.shellPath !== undefined) {
    throw new Error('dsh-default-overrides: shellPath was split into bashPath and pwshPath; rename the configured path');
  }
  if (options.blockNestedShells === true) {
    throw new Error('dsh-default-overrides: blockNestedShells PATH shims were removed; remove this option and fully restart DSH');
  }
  // Note: 禁用清单改由配置提供，默认不触碰官方工具行 — 见 .agents/notes/implemented/feature/2026-09-24-configurable-disabled-tools.md。
  const disabledTools = options.disabledTools ?? [];
  if (!Array.isArray(disabledTools) || disabledTools.some(id => typeof id !== 'string' || id.length === 0)) {
    throw new Error('dsh-default-overrides: disabledTools must be an array of standard preset row ids');
  }
  const persona = options.persona;
  const personaPresets = persona === undefined ? [] : options.personaPresets ?? DEFAULT_PERSONA_PRESETS;
  if (!Array.isArray(personaPresets) || personaPresets.some(id => typeof id !== 'string' || id.length === 0)) {
    throw new Error('dsh-default-overrides: personaPresets must be an array of agent preset ids');
  }
  const includeHarnessIdentity = options.includeHarnessIdentity;
  if (includeHarnessIdentity !== undefined && typeof includeHarnessIdentity !== 'boolean') {
    throw new Error('dsh-default-overrides: includeHarnessIdentity must be a boolean');
  }
  const persistent = shellEnabled && mode.startsWith('persistent-');
  const dialect = mode === 'bash' || mode === 'persistent-bash' ? 'bash' : 'pwsh';
  const pathKey = dialect === 'bash' ? 'bashPath' : 'pwshPath';
  // 两路径可并存；Windows Bash 的入口验证在执行器中完成，其他分支只校验当前家族。
  const shellPath = shellEnabled ? options[pathKey] : undefined;
  const windowsBash = shellEnabled && dialect === 'bash' && process.platform === 'win32';
  if (!windowsBash && shellPath !== undefined && (typeof shellPath !== 'string' || !isAbsolute(shellPath) || !existsSync(shellPath) || !statSync(shellPath).isFile())) {
    throw new Error(`dsh-default-overrides: ${pathKey} must name an existing absolute executable`);
  }
  // Note: 先确定适用范围，再校验有效值；无关配置可预先保留 — 见 .agents/notes/implemented/feature/2026-09-25-option-applicability-and-command-safety.md。
  const normalizeWindowsPaths = shellEnabled && dialect === 'bash' ? options.normalizeWindowsPaths ?? false : false;
  if (typeof normalizeWindowsPaths !== 'boolean') {
    throw new Error('dsh-default-overrides: normalizeWindowsPaths must be a boolean');
  }
  const envContext = options.envContext;
  if (envContext !== undefined && typeof envContext !== 'boolean') {
    throw new Error('dsh-default-overrides: envContext must be a boolean');
  }
  // Windows 的 Bash 两模式必须解析并验证真实 Bash，其他平台沿用官方回退。
  const officialBashFallback = shellEnabled && !persistent && dialect === 'bash' && !windowsBash && shellPath === undefined && !normalizeWindowsPaths;
  // managedShell：插件是否真的接管了这个方言通道（决定工具说明补充与 Shell 通道声明）。
  const managedShell = shellEnabled && !officialBashFallback;
  const timeoutMs = managedShell ? options.timeoutMs ?? 300000 : undefined;
  if (managedShell && (!Number.isSafeInteger(timeoutMs) || timeoutMs <= 0)) {
    throw new Error('dsh-default-overrides: timeoutMs must be a positive safe integer');
  }
  // 环境事实段是独立提示词选项：显式配置说了算；未配置时只在选了 Shell 模式才贡献（空配置仍是零影响）。
  const environmentEnabled = envContext ?? shellEnabled;
  const [{ default: AgentPreset }, { applyEntryPatches }, { default: SystemPrompt }] = await Promise.all([
    ctx.loader.import('@deepseek-ai/dsh-agent-preset'),
    ctx.loader.import('@deepseek-ai/cordis-plugin-include'),
    ctx.loader.import('@deepseek-ai/dsh-system-prompt'),
  ]);
  const patched = new WeakMap();
  // 只记录确实替换过 Shell 行的预设；persona 和工具禁用不声明通道所有权。
  const configuredShellPresets = new Set();
  let shimPath;

  function shellPatches() {
    // Note: 归一化必须在 bash 解析命令前完成，持久化模式只能靠 eval 垫片 — 见 .agents/notes/implemented/feature/2026-09-24-windows-path-normalization.md。
    const rewritePaths = normalizeWindowsPaths;
    if (rewritePaths && persistent) shimPath ??= writeBashShim();
    const backendRows = persistent ? [
      { id: 'pty', name: '@deepseek-ai/dsh-terminal' },
      {
        id: 'terminal-shell',
        name: windowsBash ? new URL('./windows-bash-terminal.mjs', import.meta.url).href : '@deepseek-ai/dsh-terminal-bash',
        config: {
          shellDialect: dialect,
          ...(shellPath === undefined ? {} : { shellPath }),
          timeoutMs,
          ...(rewritePaths ? { shellArgs: ['--noprofile', '--rcfile', shimPath, '-i'] } : {}),
        },
      },
    ] : [dialect === 'bash' ? {
      id: 'gitbash-executor',
      name: new URL('./gitbash-executor.mjs', import.meta.url).href,
      config: { shellPath, timeoutMs, normalizeWindowsPaths: rewritePaths },
    } : {
      id: 'pwsh-executor',
      name: '@deepseek-ai/dsh-pwsh-local',
      config: { ...(shellPath === undefined ? {} : { pwshPath: shellPath }), timeoutMs },
    }];
    return [
      ...SHIPPED_SHELL_ROWS.map(row => ({ ...row, disabled: true })),
      { insert: [{
        id: SHELL_GROUP_ID,
        name: 'cordis:group',
        group: true,
        isolate: { ...(persistent ? { terminals: true } : { shell: true }), ...(windowsBash ? { [BASH_RUNTIME_SERVICE]: true } : {}) },
        config: [
          ...backendRows,
          {
            id: persistent ? 'persistent-shell' : 'one-shot-shell',
            name: `@deepseek-ai/dsh-tool-${dialect}${persistent ? '-persistent' : ''}`,
            ...(persistent ? { config: { timeoutMs } } : {}),
          },
        ],
      }] },
    ];
  }

  // Note: 仅固定 persona 行，保留完整标准指引 — 见 .agents/notes/implemented/feature/2026-09-24-configurable-persona.md。
  function personaPatch(rows, presetId) {
    const matches = rows.filter(row => row.id === PERSONA_ROW.id);
    if (matches.length !== 1 || matches[0].name !== PERSONA_ROW.name || typeof matches[0].config?.prefix !== 'string') {
      throw new Error(`dsh-default-overrides: expected one ${PERSONA_ROW.id} row named ${PERSONA_ROW.name} in preset ${presetId} with a string config.prefix; review preset compatibility`);
    }
    // 行补丁整体替换 config，因此先展开当前有效值；complete 与运行时上下文按方案默认，可显式覆盖。
    return {
      id: PERSONA_ROW.id,
      name: PERSONA_ROW.name,
      config: {
        ...matches[0].config,
        ...persona,
        complete: persona.complete ?? false,
        includeRuntimeContext: persona.includeRuntimeContext ?? true,
      },
    };
  }

  ctx.on('internal/config', function (_raw, next) {
    const config = next();
    // Note: harness:identity 由全局 system-prompt 行注册，这里只改它的官方开关 — 见 .agents/notes/implemented/feature/2026-09-24-configurable-harness-identity.md。
    if (this.runtime?.callback === SystemPrompt) {
      return includeHarnessIdentity === undefined ? config : { ...config, includeHarnessIdentity };
    }
    // 行补丁分两类：Shell 与工具行仍只作用于官方 standard 预设：它是本插件声明兼容的结构基线（persona 行、tool-bash/tool-pwsh 行、行 ID 清单都在那里）。
    if (this.runtime?.callback !== AgentPreset) return config;
    const structural = config.id === 'standard';
    // Note: standard 与其他预设共用名单判断，空名单停用覆盖 — 见 .agents/notes/implemented/feature/2026-09-25-option-applicability-and-command-safety.md。
    const applyPersona = persona !== undefined && personaPresets.includes(config.id);
    const applyShell = structural && managedShell;
    if (!applyPersona && !applyShell && (!structural || disabledTools.length === 0)) return config;
    if (patched.has(config)) return patched.get(config);
    const rows = flattenRows(config.plugins);
    const patches = [];
    if (applyPersona) {
      verifyPersonaOption(persona);
      patches.push(personaPatch(rows, config.id));
    }
    if (structural) {
      // 上游行 ID 变化时明确报错，避免 applyEntryPatches 只留一条 warning 后静默不生效。
      for (const id of disabledTools) {
        if (!rows.some(row => row.id === id)) {
          throw new Error(`dsh-default-overrides: disabledTools names ${JSON.stringify(id)}, which is not a row of the standard preset`);
        }
      }
      patches.push(...disabledTools.map(id => ({ id, disabled: true })));
    }
    if (applyShell) {
      verifyShellRows(rows);
      patches.push(...shellPatches());
    }
    const result = {
      ...config,
      plugins: applyEntryPatches(config.plugins, patches, (message, ...args) => ctx.logger.warn(message, ...args)),
    };
    patched.set(config, result);
    patched.set(result, result);
    if (applyShell) configuredShellPresets.add(config.id);
    return result;
  }, { global: true });

  // Note: 环境事实段与 Shell 补丁解耦，未接管通道时也必须给出平台与工作区 — 见 .agents/notes/implemented/bug-fix/2026-09-25-environment-facts-in-every-shell-mode.md。
  if (managedShell || environmentEnabled) {
    ctx.on('system-prompt/assemble', async (_assembly, context, next) => {
      const assembly = await next();
      const agent = context.agent;
      if (!agent) return assembly;
      // 不按预设名放行也不按预设名拦截：环境事实对每个 agent 都贡献，只有本插件确实给该预设打过行补丁时才声明 Shell 通道并改写工具说明。
      const ownsChannel = managedShell && configuredShellPresets.has(ctx.agentPresets.composedPreset(agent.ctx));
      const workspace = agent.session.header.cwd;
      // Note: 探测在执行上下文发生；工具说明和环境段不能各自猜测身份 — 见 .agents/notes/implemented/feature/2026-09-25-verified-windows-bash.md。
      let facts;
      if (ownsChannel && windowsBash) {
        const runtime = ctx.agentPresets.serviceFor(agent, BASH_RUNTIME_SERVICE);
        if (!runtime) throw new Error('dsh-default-overrides: verified Bash service is unavailable in this preset revision; restart DSH and create a new session after upgrading');
        facts = await runtime.inspect(agent, context.signal);
      }
      const tools = ownsChannel
        ? assembly.tools.map(tool => tool.name === dialect
          ? { ...tool, description: `${tool.description}\n\n${shellGuidance(dialect, facts)}`, parameters: commandParameterHint(tool.parameters, dialect, facts) }
          : tool)
        : assembly.tools;
      if (!environmentEnabled) return { ...assembly, tools };
      const variables = { ...assembly.variables };
      if (workspace !== undefined) variables.dsh_overrides_workspace = workspace;
      // 只有本段真的引用 Shell 路径时才注册该变量，避免未接管通道时留下无载体的变量。
      if (ownsChannel) variables.dsh_overrides_shell_path = facts?.executable ?? shellPath ?? (dialect === 'bash' ? 'the official default bash (bashPath unset)' : 'auto-detected by the official PowerShell executor (pwshPath unset)');
      if (facts) variables.dsh_overrides_bash_runtime = bashRuntimeDescription(facts);
      return {
        ...assembly,
        tools,
        variables,
        contexts: [
          ...assembly.contexts.filter(section => section.name !== ENVIRONMENT_SECTION),
          {
            name: ENVIRONMENT_SECTION,
            text: environmentContext({ managed: ownsChannel, mode, persistent, timeoutMs, hasWorkspace: workspace !== undefined }) + (facts ? '\n{{dsh_overrides_bash_runtime}}' : ''),
          },
        ],
      };
    }, { global: true });
  }

  // 宿主 preset-standard 的 inject 必须包含本信号；不要把它加在 agentPresets 注册表上。
  ctx.provide('dshDefaultOverridesReady', true);
}
